def load(p):
    p = A / p
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def f(x, d=3):
    return "n/a" if x is None else f"{x:.{d}f}" if isinstance(x, float) else str(x)


def pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


def table(rows, cols, heads):
    out = ["| " + " | ".join(heads) + " |", "|" + "|".join("---:" if i else "---" for i in range(len(cols))) + "|"]
    for r in rows:
        out.append("| " + " | ".join(r[c] if isinstance(r.get(c), str) else f(r.get(c)) for c in cols) + " |")
    return "\n".join(out)


def pytest_counts() -> dict | None:
    p = A / "regression" / "pytest_junit.xml"
    if not p.exists():
        return None
    root = ET.parse(p).getroot()
    s = root if root.tag == "testsuite" else root.find("testsuite")
    tests, fail, err, skip = (int(s.get(k, 0)) for k in ("tests", "failures", "errors", "skipped"))
    skipped = [(c.get("classname") + "::" + c.get("name"), c.find("skipped").get("message", ""))
               for c in s.iter("testcase") if c.find("skipped") is not None]
    by_suite = {}
    for c in s.iter("testcase"):
        k = c.get("classname").split(".")[1] if "." in c.get("classname") else c.get("classname")
        by_suite[k] = by_suite.get(k, 0) + 1
    return {"tests": tests, "passed": tests - fail - err - skip, "failed": fail, "errors": err, "skipped": skip,
            "skipped_detail": skipped, "by_suite": by_suite}


def scenario_table(sc) -> str:
    rows = ["| Scenario | Expected | Result |", "|---|---|---|"]
    for k, v in sc["scenarios"].items():
        rows.append(f"| {k} | {v['expected']} | {'PASS' if v['passed'] else 'FAIL'} |")
    return "\n".join(rows)


